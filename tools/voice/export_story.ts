// Lists every spoken line of the story scenes (all chapters, both branches of every choice, every flag combination,
// the epilogue) and which of them have a recording. Run: npm run voice:story
//
// Writes:
//   tools/voice/story_lines.json   read by generate_elevenlabs.py --set story
//   src/story/voiceIndex.ts        the clips that exist on disk, so the game only asks for files that are there
// Prints a coverage table; `--check` exits 1 if any line is unrecorded (for CI once everything is voiced).
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { STORY_CHAPTERS } from '../../src/game/rules';
import { AREA_COUNT_BEFORE_PRESTIGE, findStoryChapter } from '../../src/game/progression';
import { chapterScene } from '../../src/story/chapterScene';
import { endingScene } from '../../src/story/scenes/ending';
import { PROLOGUE } from '../../src/story/scenes/prologue';
import { speakerCharacter } from '../../src/game/voiceLines';
import { Beat, CastId, Scene } from '../../src/story/types';
import { storyVoiceId } from '../../src/story/voice';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const CLIP_DIR = join(ROOT, 'public', 'assets', 'audio', 'story');

/** The story-choice flags the scripts branch on, found by reading `f.key === 'value'` in src/story. */
function flagCandidates(): Record<string, string[]> {
  const found: Record<string, Set<string>> = {};
  const walk = (dir: string): string[] =>
    readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : e.name.endsWith('.ts') && !e.name.includes('.test.') ? [join(dir, e.name)] : []));
  for (const file of walk(join(ROOT, 'src', 'story'))) {
    for (const m of readFileSync(file, 'utf8').matchAll(/\b(?:f|flags)\.(\w+)\s*===\s*'(\w+)'/g)) (found[m[1]] ??= new Set()).add(m[2]);
  }
  // Scripts also test `if (f.key)`, and take the other branch for any value that is not the one compared.
  return Object.fromEntries(Object.entries(found).map(([k, v]) => [k, ['', ...v, 'other']]));
}

function* flagCombos(candidates: Record<string, string[]>): Generator<Record<string, string>> {
  const keys = Object.keys(candidates);
  const pick = (i: number, acc: Record<string, string>): Generator<Record<string, string>> => {
    if (i === keys.length) return (function* () { yield { ...acc }; })();
    return (function* () {
      for (const v of candidates[keys[i]]) {
        const next = { ...acc };
        if (v) next[keys[i]] = v;
        yield* pick(i + 1, next);
      }
    })();
  };
  yield* pick(0, {});
}

/** The epilogue's keepsake shelf joins whichever hosts were met (128 variants of one line): left unvoiced. */
const UNVOICED_BEATS = new Set(['shelf_list']);

interface Entry { id: string; speaker: string; ar: string; en: string; scenes: Set<string> }

function collect(): { entries: Map<string, Entry>; explicit: Set<string> } {
  const entries = new Map<string, Entry>();
  const explicit = new Set<string>();
  const add = (sceneId: string, b: Beat) => {
    if (UNVOICED_BEATS.has(b.id) || !b.textAr.trim()) return;
    if (b.voice && sceneId === 'prologue') { explicit.add(b.voice); return; }
    const id = storyVoiceId(b.speaker, b.textAr);
    const seen = entries.get(id);
    if (seen && (seen.ar !== b.textAr || seen.speaker !== (b.speaker ?? 'narr'))) throw new Error(`voice id collision: ${id}`);
    const e = seen ?? { id, speaker: b.speaker ?? 'narr', ar: b.textAr, en: b.textEn, scenes: new Set<string>() };
    e.scenes.add(sceneId);
    entries.set(id, e);
  };
  const addScene = (s: Scene, label: string) => s.beats.forEach((b) => add(label, b));

  addScene(PROLOGUE, 'prologue');
  const chapters = [...STORY_CHAPTERS, ...Array.from({ length: AREA_COUNT_BEFORE_PRESTIGE }, (_, i) => findStoryChapter(`area_${i}`))].filter((c) => !!c);
  const combos = [...flagCombos(flagCandidates())];
  for (const flags of combos) {
    for (const c of chapters) addScene(chapterScene(c!, speakerCharacter(c!.speakerEn) as CastId | null, flags), c!.id);
    addScene(endingScene(flags), 'ending');
  }
  return { entries, explicit };
}

const { entries, explicit } = collect();
const lines = [...entries.values()].sort((a, b) => a.speaker.localeCompare(b.speaker) || a.id.localeCompare(b.id));
const has = (id: string) => existsSync(join(CLIP_DIR, `${id}.mp3`));

writeFileSync(
  join(ROOT, 'tools', 'voice', 'story_lines.json'),
  JSON.stringify({ lines: lines.map((l) => ({ id: l.id, speaker: l.speaker, ar: l.ar, en: l.en, scenes: [...l.scenes].sort(), recorded: has(l.id) })) }, null, 2) + '\n'
);

const recorded = lines.filter((l) => has(l.id)).map((l) => l.id).sort();
writeFileSync(
  join(ROOT, 'src', 'story', 'voiceIndex.ts'),
  `// Generated by \`npm run voice:story\` (tools/voice/export_story.ts): the story clips that exist in\n// public/assets/audio/story/. Do not edit by hand.\nexport const STORY_CLIP_IDS: readonly string[] = ${JSON.stringify(recorded, null, 2)};\n`
);

const bySpeaker = new Map<string, { lines: number; chars: number; missing: number }>();
for (const l of lines) {
  const s = bySpeaker.get(l.speaker) ?? { lines: 0, chars: 0, missing: 0 };
  s.lines++; s.chars += l.ar.length;
  if (!has(l.id)) s.missing++;
  bySpeaker.set(l.speaker, s);
}
console.table(Object.fromEntries(bySpeaker));
const missing = lines.filter((l) => !has(l.id));
console.log(`${lines.length} lines to voice (+${explicit.size} prologue clips named by hand): ${lines.length - missing.length} recorded, ${missing.length} missing, ${missing.reduce((n, l) => n + l.ar.length, 0)} characters to generate`);
if (process.argv.includes('--check') && missing.length) process.exit(1);
